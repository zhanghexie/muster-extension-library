import assert from 'node:assert/strict';
import { createDomainRuntime } from '../library/domain.mjs';
const files = new Map(); let fail = false;
const broker = async (method,args) => {
  if(method==='data.read')return files.has(args[0])?{content:files.get(args[0])}:null;
  if(method==='data.write'){if(fail&&args[0]==='library/index.json')throw new Error('disk unavailable');files.set(args[0],args[1]);return true;}
  throw new Error('Unexpected '+method);
};
const context={actor:'human',signal:new AbortController().signal};
const runtime=createDomainRuntime({broker});
assert.equal((await runtime.getSnapshot()).state.entries.length,0,'no bundled book content or fake online catalog');
const book={title:'原文书籍',author:'作者',format:'epub',sourceName:'book.epub',chapters:[{title:'第一章',paragraphs:['学而时习之','有朋自远方来']},{title:'第二章',paragraphs:['温故而知新','可以为师矣']}]};
const imported=await runtime.execute('book.import',{book},context);const id=imported.result.bookId;
assert.equal((await runtime.execute('book.import',{book},context)).result.duplicate,true);
assert.equal((await runtime.query('book.toc',{bookId:id})).chapters.length,2);
assert.deepEqual((await runtime.query('book.content',{bookId:id,chapterIndex:1})).paragraphs,book.chapters[1].paragraphs);
await runtime.execute('book.open',{bookId:id},context);
await runtime.execute('book.progress',{bookId:id,chapterIndex:1,paragraphIndex:1,offset:.3,percent:.6},context);
await runtime.execute('book.bookmark',{bookId:id,chapterIndex:1,paragraphIndex:1},context);
await runtime.execute('reader.settings',{settings:{fontSize:25,paper:'paper'}},context);
const saved=await runtime.getSnapshot();
fail=true;
await assert.rejects(()=>runtime.execute('book.progress',{bookId:id,chapterIndex:0,paragraphIndex:0,offset:0,percent:0},context),/disk unavailable/);
assert.deepEqual((await runtime.getSnapshot()).state,saved.state,'failed persistence must not publish an unsaved reading position');
fail=false;
await assert.rejects(()=>runtime.execute('book.progress',{bookId:id,chapterIndex:2,paragraphIndex:0,offset:0,percent:0},context),/章节序号/);
await assert.rejects(()=>runtime.execute('book.progress',{bookId:id,chapterIndex:1,paragraphIndex:99,offset:0,percent:0},context),/阅读位置/);
assert.equal((await runtime.query('library.search',{q:'温故'})).matches[0].chapterIndex,1);
await runtime.close();
const reopened=createDomainRuntime({broker});
const toc=await reopened.query('book.toc',{bookId:id});
assert.deepEqual(toc.entry.progress,saved.state.entries[0].progress);
assert.equal(toc.bookmarks[0].text,'可以为师矣');
assert.equal((await reopened.getSnapshot()).state.reader.fontSize,25);
assert.equal((await reopened.getSnapshot()).state.lastBookId,id);
await reopened.execute('book.open',{bookId:id,chapterIndex:1},context);
assert.equal((await reopened.query('book.toc',{bookId:id})).entry.progress.percent,0,'choosing a chapter explicitly opens its beginning');
await reopened.execute('book.remove',{bookId:id},context);
assert.equal((await reopened.getSnapshot()).state.entries.length,0);
await reopened.close();
const corrupt=createDomainRuntime({broker:async()=>({content:'{bad'})});
await assert.rejects(()=>corrupt.getSnapshot(),/未重置书架/);await corrupt.close();
console.log('extensions-library: import, persistence, bookmarks, search and failure rollback ok');
